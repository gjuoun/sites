// Generates packages/ui/src/styles/tokens.css from palette/bigface.json.
//
// The package ships the Bigface palette as the default theme, but the palette file stays the single
// source: this script writes the CSS and `bun run theme:sync` is re-run whenever the palette moves.
// A consumer that wants its own colours imports theme.css (structure only) and sets --bf-* itself.
//
// `bun run --cwd packages/ui theme:sync`   rewrite tokens.css in place
// `bun run --cwd packages/ui theme:check`  fail when tokens.css is stale (CI uses this)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface PaletteLike {
  colors: Record<string, { hex: string }>;
  ansi: Record<string, { hex: string }>;
}

const kebab = (name: string): string =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/_/g, "-")
    .toLowerCase();

/** The exact text of tokens.css for a palette. Deterministic: input order only, no timestamps. */
export function renderTokens(palette: PaletteLike): string {
  const colors = Object.entries(palette.colors).map(
    ([name, c]) => `  --bf-${kebab(name)}: ${c.hex.toLowerCase()};`,
  );
  const ansi = Object.entries(palette.ansi).map(
    ([name, c]) => `  --bf-ansi-${kebab(name)}: ${c.hex.toLowerCase()};`,
  );
  return [
    "/* Generated by packages/ui/scripts/gen-tokens.ts from palette/bigface.json. Do not edit.",
    "   Bigface's default theme: import it after theme.css, or skip it and set your own --bf-* values. */",
    ":root {",
    ...colors,
    ...ansi,
    "  --ink-on-bright: var(--bf-bg);",
    "}",
    "",
  ].join("\n");
}

const here = import.meta.dir;
export const tokensPath = join(here, "../src/styles/tokens.css");
const palettePath = join(here, "../../bigface-tokens/palette/bigface.json");

if (import.meta.main) {
  const palette = JSON.parse(readFileSync(palettePath, "utf8")) as PaletteLike;
  const next = renderTokens(palette);
  if (process.argv.includes("--check")) {
    const current = readFileSync(tokensPath, "utf8");
    if (current !== next) {
      console.error(
        "tokens.css is stale: run `bun run --cwd packages/ui theme:sync` and commit the result",
      );
      process.exit(1);
    }
    console.log("tokens.css is up to date");
  } else {
    writeFileSync(tokensPath, next);
    console.log(`wrote ${tokensPath}`);
  }
}
