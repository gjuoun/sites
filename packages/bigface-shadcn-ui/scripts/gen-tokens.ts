// Generates the Bigface package's colour artefacts from the one palette and the role map:
//
//   src/themes/bigface.css   the Bigface theme, shadcn's two blocks: light values, then dark values
//
//   bun run theme:sync   rewrite it in place
//   bun run theme:check  fail when it is stale (CI uses this)
//
// A role names a palette colour. Like shadcn's :root and .dark, the light block holds every role's light
// hex and the dark block restates every role with its dark hex; the mode is the data-mode attribute.
// Nothing here writes a size, a radius, a shadow geometry, a font or a
// motion value: those are Tailwind's and shadcn's own.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REQUIRED, THEMES, type Theme } from "../src/themes/roles.ts";

/** One mode of palette/palette.json: the colour names, and the ANSI slots that alias them. */
export interface PaletteMode {
	colors: Record<string, string>;
	ansi: Record<string, string>;
}

/** palette/palette.json: fifteen colours in a light and a dark mode, plus the syntax role map. */
export interface PaletteLike {
	name: string;
	modes: Record<"light" | "dark", PaletteMode>;
	syntax: Record<string, string>;
}

const hexOf = (mode: PaletteMode, name: string): string => {
	const hex = mode.colors[name];
	if (!hex) throw new Error("no palette colour named " + name);
	return hex.toLowerCase();
};

/**
 * A theme, as shadcn's two blocks: every role's light hex on :root and [data-mode="light"] (so a light
 * panel inside a dark page is light), then every role's dark hex on [data-mode="dark"].
 */
export function renderThemeFile(theme: Theme, light: PaletteMode, dark: PaletteMode): string {
	if (!theme.isDefault) throw new Error(theme.id + ": only the default theme is generated");
	const decls = (mode: PaletteMode) =>
		REQUIRED.map((role) => {
			const paletteName = theme.roles[role];
			if (!paletteName) throw new Error(theme.id + ": missing role " + role);
			// Every value is the palette's own in both blocks: no role is derived, mixed or darkened.
			return "  --theme-" + role + ": " + hexOf(mode, paletteName) + ";";
		});
	const extra = Object.keys(theme.roles).filter((k) => !(REQUIRED as readonly string[]).includes(k));
	if (extra.length) throw new Error(theme.id + ": unknown roles " + extra.join(", "));
	return [
		"/* Generated by packages/bigface-shadcn-ui/scripts/gen-tokens.ts from src/themes/roles.ts and",
		"   palette/palette.json. Colour only: the light block, then the dark block. Do not edit: change the role",
		"   map, then run theme:sync. */",
		"",
		':root, [data-mode="light"] {',
		...decls(light),
		"}","",
		'[data-mode="dark"] {',
		...decls(dark),
		"}","",
	].join("\n");
}

const here = import.meta.dir;
export const themesDir = join(here, "../src/themes");
const palettePath = join(here, "../../bigface-tokens/palette/palette.json");

/** Every file theme:sync writes, as path to contents. */
export function renderAll(palette: PaletteLike): Record<string, string> {
	const files: Record<string, string> = {};
	for (const theme of THEMES) {
		files[join(themesDir, theme.id + ".css")] = renderThemeFile(theme, palette.modes.light, palette.modes.dark);
	}
	return files;
}

const read = (p: string) => JSON.parse(readFileSync(p, "utf8")) as PaletteLike;

if (import.meta.main) {
	const files = renderAll(read(palettePath));
	const check = process.argv.includes("--check");
	let stale = 0;
	for (const [path, next] of Object.entries(files)) {
		const current = existsSync(path) ? readFileSync(path, "utf8") : "";
		if (!check) {
			writeFileSync(path, next);
			console.log("wrote " + path);
			continue;
		}
		if (current !== next) {
			console.error("stale: " + path);
			stale++;
		}
	}
	if (check) {
		if (stale) {
			console.error(stale + " file(s) stale: run theme:sync");
			process.exit(1);
		}
		console.log("theme files are up to date (" + Object.keys(files).length + ")");
	}
}
