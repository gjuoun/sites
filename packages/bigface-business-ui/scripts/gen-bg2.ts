#!/usr/bin/env bun
// Generates the BG2 alias layer: one module per stock file in src/components/ui, each a pure re-export under the BG2
// name. A BG2 name is BG2 + the stock export name, verbatim (ruling Q3-A: BG2buttonVariants, BG2useSidebar).
//
//   bun run bg2:sync    write src/bg2/<stem>.ts for every stock file
//   bun run bg2:check   fail when any module differs from the render, or a stale module is left behind
//
// Syntactic on purpose: the stock files have no re-exports and no default export, and the checker in the test
// fails closed on anything else. A type-only export (export type, export interface, or export { type X }) is written
// as export type, so it stays erased at runtime.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const pkg = join(import.meta.dir, "..");
export const UI = join(pkg, "src/components/ui");
export const OUT = join(pkg, "src/bg2");

export interface Export {
	/** The export name in components/ui. */
	stock: string;
	/** The BG2 name: BG2 + stock. */
	bg2: string;
	/** True for a type-only export (erased at runtime). */
	type: boolean;
}

export interface ModuleSurface {
	/** The stock file name, e.g. button.tsx. */
	file: string;
	exports: Export[];
}

const hasExport = (node: ts.Node): boolean =>
	(ts.canHaveModifiers(node) ? ts.getModifiers(node) ?? [] : []).some((m) => m.kind === ts.SyntaxKind.ExportKeyword);

/** The exports of one stock file, in source order, with the kind of each. */
function fileSurface(file: string): Export[] {
	const text = readFileSync(join(UI, file), "utf8");
	const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true, ts.ScriptKind.TSX);
	const out: Export[] = [];
	const local = new Map<string, boolean>(); // local declaration name -> is a type
	const push = (stock: string, type: boolean) => out.push({ stock, bg2: "BG2" + stock, type });

	for (const st of sf.statements) {
		if (ts.isExportAssignment(st)) throw new Error(file + ": default export, not supported by the BG2 layer");
		if (ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st) || ts.isEnumDeclaration(st)) {
			if (!st.name) throw new Error(file + ": anonymous declaration");
			local.set(st.name.text, false);
			if (hasExport(st)) push(st.name.text, false);
		} else if (ts.isVariableStatement(st)) {
			for (const d of st.declarationList.declarations) {
				if (!ts.isIdentifier(d.name)) throw new Error(file + ": destructured export, not supported");
				local.set(d.name.text, false);
				if (hasExport(st)) push(d.name.text, false);
			}
		} else if (ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st)) {
			local.set(st.name.text, true);
			if (hasExport(st)) push(st.name.text, true);
		}
	}
	for (const st of sf.statements) {
		if (!ts.isExportDeclaration(st)) continue;
		if (st.moduleSpecifier) throw new Error(file + ": re-export from another module, not supported by the BG2 layer");
		for (const spec of st.exportClause && ts.isNamedExports(st.exportClause) ? st.exportClause.elements : []) {
			const name = spec.name.text;
			const isType = st.isTypeOnly || spec.isTypeOnly || local.get(spec.propertyName?.text ?? name) === true;
			if (spec.propertyName) throw new Error(file + ": renamed export " + name + ", not supported");
			push(name, isType);
		}
	}
	const seen = new Set<string>();
	for (const e of out) {
		if (seen.has(e.stock)) throw new Error(file + ": duplicate export " + e.stock);
		seen.add(e.stock);
	}
	return out;
}

/** The whole surface, one entry per stock file, sorted by file name. */
export function surface(): ModuleSurface[] {
	return readdirSync(UI)
		.filter((f) => f.endsWith(".tsx"))
		.sort()
		.map((file) => ({ file, exports: fileSurface(file) }));
}

/** The text of one module. */
export function renderModule(m: ModuleSurface): string {
	const from = "../components/ui/" + m.file.replace(/\.tsx$/, "");
	const values = m.exports.filter((e) => !e.type).map((e) => e.stock + " as " + e.bg2);
	const types = m.exports.filter((e) => e.type).map((e) => e.stock + " as " + e.bg2);
	const lines = [
		"// Generated by packages/bigface-business-ui/scripts/gen-bg2.ts from src/components/ui/" + m.file + ". Do not edit.",
		"// Pure aliases: each BG2 name is the stock binding, not a copy. Plain names still import from components/ui.",
	];
	if (values.length) lines.push('export { ' + values.join(", ") + ' } from "' + from + '";');
	if (types.length) lines.push('export type { ' + types.join(", ") + ' } from "' + from + '";');
	return lines.join("\n") + "\n";
}

/** Every file src/bg2 must hold: path to contents. */
export function renderAll(): Record<string, string> {
	const files: Record<string, string> = {};
	for (const m of surface()) files[join(OUT, m.file.replace(/\.tsx$/, ".ts"))] = renderModule(m);
	return files;
}

if (import.meta.main) {
	const check = Bun.argv.includes("--check");
	const want = renderAll();
	const names = surface().reduce((n, m) => n + m.exports.length, 0);
	if (check) {
		const problems: string[] = [];
		for (const [path, text] of Object.entries(want)) {
			if (!existsSync(path) || readFileSync(path, "utf8") !== text) problems.push("stale: " + path);
		}
		for (const f of readdirSync(OUT)) if (!f.endsWith(".test.ts") && !Object.keys(want).includes(join(OUT, f))) problems.push("stale file: " + f);
		if (problems.length) {
			for (const p of problems) console.error(p);
			console.error("bg2:check: FAIL (" + problems.length + ")");
			process.exit(1);
		}
		console.log("BG2 ok names=" + names + " modules=" + Object.keys(want).length);
	} else {
		for (const [path, text] of Object.entries(want)) writeFileSync(path, text);
		console.log("BG2 wrote names=" + names + " modules=" + Object.keys(want).length);
	}
}
